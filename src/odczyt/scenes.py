"""Scene code layout: parts per chapter, scaffold files and the Remotion registry."""

import re
from pathlib import Path

from odczyt.episode import Episode

PLACEHOLDER = """import type { FC } from "react";

export const scenes: Record<string, FC> = {};
"""


def plan_parts(storyboard: dict) -> list[tuple[str, list[str]]]:
    """Split scenes into one part per chapter; chapterless scenes join their neighbor."""
    groups: list[tuple[str | None, list[str]]] = []
    pending: list[str] = []
    for scene in storyboard["scenes"]:
        chapter = scene.get("chapter")
        if chapter is None:
            if groups:
                groups[-1][1].append(scene["id"])
            else:
                pending.append(scene["id"])
            continue
        if groups and groups[-1][0] == chapter:
            groups[-1][1].append(scene["id"])
        else:
            groups.append((chapter, [*pending, scene["id"]]))
            pending = []
    if pending:
        groups.append((None, pending))
    return [(f"part{i}", ids) for i, (_, ids) in enumerate(groups, 1)]


def part_of_scene(parts: list[tuple[str, list[str]]]) -> dict[str, str]:
    return {scene: part for part, ids in parts for scene in ids}


def is_placeholder(path: Path) -> bool:
    return not path.exists() or path.read_text(encoding="utf-8") == PLACEHOLDER


def index_source(parts: list[str]) -> str:
    imports = "".join(f'import {{ scenes as {p} }} from "./{p}";\n' for p in parts)
    spread = ", ".join(f"...{p}" for p in parts)
    return (
        'import type { FC } from "react";\n'
        f"{imports}\n"
        f"export const scenes: Record<string, FC> = {{ {spread} }};\n"
    )


def registry_source(episodes_dir: Path) -> str:
    slugs = sorted(p.parent.name for p in episodes_dir.glob("*/scenes.tsx"))
    names = {s: "ep" + re.sub(r"\W", "_", s) for s in slugs}
    imports = "".join(f'import {{ scenes as {names[s]} }} from "./{s}/scenes";\n' for s in slugs)
    entries = "".join(f'  "{s}": {names[s]},\n' for s in slugs)
    return (
        'import type { FC } from "react";\n'
        f"{imports}\n"
        "/** Episode slug → scene id → scene component. Generated by `odczyt`. */\n"
        "export const EPISODES: Record<string, Record<string, FC>> = {\n"
        f"{entries}"
        "};\n"
    )


def write_if_changed(path: Path, text: str) -> None:
    if not path.exists() or path.read_text(encoding="utf-8") != text:
        path.write_text(text, encoding="utf-8")


def scaffold(ep: Episode) -> list[tuple[str, list[str]]]:
    """Create placeholder part files, the episode index and the registry; return the parts."""
    parts = plan_parts(ep.storyboard())
    ep.scenes_dir.mkdir(parents=True, exist_ok=True)
    for part, _ in parts:
        path = ep.scenes_dir / f"{part}.tsx"
        if not path.exists():
            path.write_text(PLACEHOLDER, encoding="utf-8")
    write_if_changed(ep.scenes_dir / "scenes.tsx", index_source([p for p, _ in parts]))
    write_if_changed(ep.scenes_dir.parent / "registry.ts", registry_source(ep.scenes_dir.parent))
    return parts


def still_scene(name: str) -> str:
    """Scene id of a still named NN-scene--cue (intro/outro stills belong to no scene)."""
    return name.split("-", 1)[1].split("--")[0] if "--" in name else ""


def chunk_stills(names: list[str], size: int) -> list[list[str]]:
    """Group still names into review chunks of about `size`, never splitting a scene."""
    chunks: list[list[str]] = []
    current: list[str] = []
    scene = None
    for name in sorted(names):
        s = still_scene(name)
        if current and s != scene and len(current) >= size:
            chunks.append(current)
            current = []
        current.append(name)
        scene = s
    if current:
        chunks.append(current)
    return chunks
